"""Part 1 acceptance: recall and precision of reconcile against the Kestrel answer key -> reports/reconciliation.md.

This is the only module that reads the answer key (evaluation only: never prompts, extraction or reconcile logic;
tests/test_claims.py enforces it). Every number in the report is read or computed here from files the pipeline
produced: data/facts/discrepancies.jsonl, data/facts/facts.duckdb (claims, tier-3 facts), data/facts/build_log.json,
data/dataroom/{deal}/export/manifest.csv and data/dataroom/{deal}/answer_key.yaml.

Alignment: a key claim is aligned to one of our claims with the same document, page and metric (the closest value
if several). A status other than match and no_fact is a flag. Per category: recall (caught) = key traps whose aligned
claim is flagged; recall (exact) = whose aligned claim has exactly the expected status; precision = TP / (TP + FP),
TP = our flagged claims aligned to that category's key trap, FP = our flagged claims with the category's metric that
are aligned to no key trap (T-*) at all. Keys compared by value only; the
key's unit field is never used (DECISIONS 2026-11-05).
"""
from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path

import duckdb
import yaml

from src.facts.reconcile import fact_for, index_facts, load

CATEGORIES = ["T-GROWTH", "T-RUNRATE", "T-CONC", "T-NRR", "T-PERIOD"]
FLAGS = {"discrepancy", "definition_mismatch", "period_mismatch"}


def align(key_claims: list[dict], ours: list[dict], doc_ids: dict[str, str]) -> dict[str, dict | None]:
    """key claim_id -> our claim (with its reconcile record) or None."""
    out = {}
    for k in key_claims:
        cands = [o for o in ours if o["doc_id"] == doc_ids[k["doc"]] and o["page"] == k.get("page")
                 and o["metric"] == k["metric"]]
        out[k["claim_id"]] = min(cands, key=lambda o: abs(o["value"] - k["claim_value"])) if cands else None
    return out


def score(key_claims: list[dict], ours: list[dict], aligned: dict) -> dict[str, dict]:
    """Precision per category: true positives = our flagged claims aligned to this category's trap; false positives
    = our flagged claims with the category's metric that are aligned to no key trap at all (a flagged claim aligned
    to another category's trap is a correct catch, not a false positive here)."""
    any_trap_ids = {aligned[k["claim_id"]]["claim_id"] for k in key_claims
                    if str(k.get("trap", "")).startswith("T-") and aligned[k["claim_id"]]}
    res = {}
    for cat in CATEGORIES:
        traps = [k for k in key_claims if k.get("trap") == cat]
        metrics = {k["metric"] for k in traps}
        hit_ids = {aligned[k["claim_id"]]["claim_id"] for k in traps if aligned[k["claim_id"]]}
        caught = sum(1 for k in traps if aligned[k["claim_id"]] and aligned[k["claim_id"]]["status"] in FLAGS)
        exact = sum(1 for k in traps if aligned[k["claim_id"]] and
                    aligned[k["claim_id"]]["status"] == k["expected_status"])
        flagged = [o for o in ours if o["metric"] in metrics and o["status"] in FLAGS]
        tp = sum(1 for o in flagged if o["claim_id"] in hit_ids)
        fp = sum(1 for o in flagged if o["claim_id"] not in any_trap_ids)
        res[cat] = {"traps": len(traps), "caught": caught, "exact": exact, "flagged": tp + fp, "tp": tp}
    return res


def pct(n: int, d: int) -> str:
    return f"{n}/{d} ({n / d:.0%})" if d else f"{n}/{d} (n/a)"


def gap_text(g) -> str:
    return "" if g is None else f"{g:+.1%}"


def write_report(deal: str, root: Path, db: Path, disc: Path, build_log: Path, out: Path) -> None:
    export = root / deal / "export"
    manifest = list(csv.DictReader(open(export / "manifest.csv", encoding="utf-8")))
    doc_ids = {m["file"]: m["accession"] for m in manifest}
    key = yaml.safe_load(open(root / deal / "answer_key.yaml", encoding="utf-8"))
    recs = {r["claim_id"]: r for r in (json.loads(l) for l in open(disc, encoding="utf-8"))}
    con = duckdb.connect(str(db), read_only=True)
    claims = load(con, "claims", deal)
    facts = load(con, "facts", deal, "AND tier = 3")
    con.close()
    ours = [{**c, **recs[c["claim_id"]]} for c in claims if c["claim_id"] in recs]
    aligned = align(key["claims"], ours, doc_ids)
    sc = score(key["claims"], ours, aligned)
    log = json.loads(Path(build_log).read_text(encoding="utf-8"))
    clog = log["claims"][deal]
    xlog = next(iter(log["dataroom"][deal].values()))
    idx = index_facts(facts)
    status_counts = {s: sum(1 for r in recs.values() if r["status"] == s)
                     for s in ("match", "discrepancy", "definition_mismatch", "period_mismatch", "no_fact")}

    L = [f"# Reconciliation: {deal}", "",
         "Brief Part 1 items 5-6 and acceptance. Generated by `src/facts/reconcile_eval.py` (reconcile stage) from "
         "`data/facts/discrepancies.jsonl`, `data/facts/facts.duckdb`, `data/facts/build_log.json`, "
         f"`data/dataroom/{deal}/export/manifest.csv` and `data/dataroom/{deal}/answer_key.yaml` (the public "
         "practice key, read only here). Every number below comes from those files.", "",
         "## Recall and precision on the trap categories reconciliation can catch", "",
         "A claim is *flagged* when its status is discrepancy, definition_mismatch or period_mismatch. Recall "
         "(caught): key traps whose aligned claim is flagged. Recall (exact): whose aligned claim has exactly the "
         "expected status. Precision: TP / (TP + FP), where TP = our flagged claims aligned to that category's trap "
         "and FP = our flagged claims with the category's metric that are aligned to no key trap at all (a claim "
         "aligned to another category's trap is a correct catch, not a false positive). Alignment: same document, "
         "page and metric.", "",
         "| Category | Key traps | Recall (caught) | Recall (exact status) | Precision |", "|---|---|---|---|---|"]
    tot = {k: sum(v[k] for v in sc.values()) for k in ("traps", "caught", "exact", "flagged", "tp")}
    for cat in CATEGORIES:
        v = sc[cat]
        L.append(f"| {cat} | {v['traps']} | {pct(v['caught'], v['traps'])} | {pct(v['exact'], v['traps'])} | "
                 f"{pct(v['tp'], v['flagged'])} |")
    L.append(f"| **All five** | {tot['traps']} | {pct(tot['caught'], tot['traps'])} | "
             f"{pct(tot['exact'], tot['traps'])} | {pct(tot['tp'], tot['flagged'])} |")
    L += ["", "## Every key claim and our result", "",
          "| Key claim | Trap | Expected | Our claim | Our status | Gap | Severity |", "|---|---|---|---|---|---|---|"]
    for k in key["claims"]:
        o = aligned[k["claim_id"]]
        L.append(f"| {k['claim_id']} | {k.get('trap')} | {k['expected_status']} | "
                 + (f"{o['claim_id']} | {o['status']} | {gap_text(o['gap'])} | {o['severity'] or ''} |" if o
                    else "not extracted | | | |"))
    L += ["", "## All reconcile records", "",
          f"{len(recs)} claims: " + ", ".join(f"{s} {n}" for s, n in status_counts.items()) + ".", "",
          "| Claim | Document | Page | Metric | Period | Status | Gap | Severity | Claim text |",
          "|---|---|---|---|---|---|---|---|---|"]
    for o in sorted(ours, key=lambda o: (o["doc_id"], o["page"] if o["page"] is not None else 10**6, o["claim_id"])):
        L.append(f"| {o['claim_id']} | {o['doc_id']} | {o['page'] if o['page'] is not None else ''} | "
                 f"{o['metric'] or ''} | {o['period']} | {o['status']} | {gap_text(o['gap'])} | {o['severity'] or ''} | "
                 f"{' '.join(o['claim_text'].split())} |")
    derived = [o for o in ours if o["metric"] in ("revenue_growth", "subscription_share")]
    L += ["", "## Derived comparisons (computed from tier-3 facts)", "",
          "| Claim | Metric | Period | Computed value | Input facts |", "|---|---|---|---|---|"]
    for o in derived:
        hit = fact_for(o["metric"], o["fiscal_year"], o["fiscal_period"], idx)
        L.append(f"| {o['claim_id']} | {o['metric']} | {o['period']} | "
                 + (f"{hit[0]:.4f} | {', '.join(hit[2])} |" if hit else "none | |"))
    L += ["", "## Fiscal year definition", "",
          f"Fiscal year end detected from the deal's tier-3 FY facts: {clog['fiscal_year_end']} (workbook statement "
          f"cells: {', '.join(xlog['fye_cells'])}). Calendar-period claims flagged period_mismatch: "
          f"{sum(1 for o in ours if o['period_basis'] == 'calendar' and o['status'] == 'period_mismatch')}.", "",
          "## Data-quality counts", "",
          "| Count | Value | Source |", "|---|---|---|",
          f"| Hidden sheets skipped (seller xlsx) | {len(xlog['hidden_sheets_skipped'])} "
          f"({', '.join(h['sheet'] for h in xlog['hidden_sheets_skipped'])}) | build_log.json dataroom |",
          f"| Inconsistent repeated iXBRL tag groups | {log['totals']['inconsistent_groups']} | build_log.json totals |",
          f"| companyfacts cross-check mismatches | {log['totals']['mismatched']} of {log['totals']['compared']} "
          f"compared | build_log.json totals |",
          f"| Unconvertible iXBRL tags skipped | {log['totals']['tags_unconvertible_skipped']} | build_log.json totals |",
          f"| Claims dropped (quote not found in a block) | "
          f"{sum(len(d['dropped']) for d in clog['documents'].values())} | build_log.json claims |"]
    for d, v in clog["documents"].items():
        L.append(f"| Blocks left out of extraction, {v['file']} ({d}) | {v['blocks_left_out']} | build_log.json claims |")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"[INFO] reconcile_eval {deal}: " + "; ".join(f"{c} caught {sc[c]['caught']}/{sc[c]['traps']}" for c in CATEGORIES)
          + f" -> {out}")


def main() -> None:
    ap = argparse.ArgumentParser(description="Part 1 reconciliation report against the Kestrel answer key")
    ap.add_argument("--deal", default="kestrel")
    ap.add_argument("--dataroom", default="data/dataroom")
    ap.add_argument("--db", default="data/facts/facts.duckdb")
    ap.add_argument("--discrepancies", default="data/facts/discrepancies.jsonl")
    ap.add_argument("--build-log", default="data/facts/build_log.json")
    ap.add_argument("--out", default="reports/reconciliation.md")
    a = ap.parse_args()
    write_report(a.deal, Path(a.dataroom), Path(a.db), Path(a.discrepancies), Path(a.build_log), Path(a.out))


if __name__ == "__main__":
    main()
